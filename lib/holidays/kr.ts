/** 공휴일 데이터가 존재하는 연도 범위 (밖이면 항상 null). */
export const HOLIDAY_YEARS = { min: 2025, max: 2027 } as const;

/** "YYYY-MM-DD" → 공휴일 명칭 | null */
export function krHolidayName(iso: string): string | null {
  return HOLIDAYS[iso] ?? null;
}

/** UTC 자정 Date → 공휴일 명칭 | null */
export function krHolidayNameOf(date: Date): string | null {
  return krHolidayName(ymd(date));
}

/** 공휴일 여부 (주말과 무관). 연차 일수 계산의 isHoliday 프레디킷으로 사용. */
export function isKrHoliday(date: Date): boolean {
  return krHolidayNameOf(date) !== null;
}
